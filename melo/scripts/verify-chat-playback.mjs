import assert from 'node:assert/strict';
import { chatMusicIntent, chatMusicCandidates, voicePlaybackRequest } from '../lib/music/chat-playback.ts';
import { playableTracks, catalog } from '../data/music/catalog.ts';
const summer = playableTracks.find(t => t.title === '夏天');
assert.equal(chatMusicIntent('今天有点累').action, 'recommend');
assert.equal(chatMusicIntent('今天很累，帮我放一首歌').action, 'play');
assert.equal(chatMusicIntent('我不想听歌，先陪我聊聊').action, 'recommend');
assert.equal(chatMusicIntent('先别播放，推荐一首歌就好').action, 'recommend');
assert.equal(chatMusicIntent('我不想听纯音乐，帮我放首人声歌').action, 'play');
assert.equal(chatMusicIntent('我想听你说说建议').action, 'recommend');
assert.equal(chatMusicIntent('暂停音乐').action, 'pause');
assert.equal(chatMusicIntent('继续播放').action, 'resume');
assert.equal(chatMusicIntent('换一首').action, 'next');
assert.equal(chatMusicIntent('我今天暂停了工作').action, 'recommend');
assert.equal(chatMusicCandidates('播放《夏天》', {mood:'sad'}, playableTracks, catalog).tracks[0].id, summer.id);
assert.equal(chatMusicCandidates('播放《不存在的歌曲xyz》', {mood:'calm'}, playableTracks, catalog).unavailable, '不存在的歌曲xyz');
const unplayable = catalog.find(t => t.source === 'qq-music');
assert.equal(chatMusicCandidates(`播放《${unplayable.title}》`, {mood:'calm'}, playableTracks, catalog).unavailable, unplayable.title);
const next = chatMusicCandidates('换一首', {mood:'calm'}, playableTracks, catalog, summer.id);
assert(!next.tracks.some(t => t.id === summer.id));
assert(next.tracks.every(t => playableTracks.some(p => p.id === t.id)));
assert.equal(voicePlaybackRequest('帮我放一首', false, '听听《稻香》', playableTracks), null);
assert.equal(voicePlaybackRequest('今天有点累', true, '听听《稻香》', playableTracks), null);
const voice = voicePlaybackRequest('我想听，但我想你帮我放一首。', true, '要不要听听《稻香》？', playableTracks);
assert.equal(voice.suggestedTrackId, playableTracks.find(t=>t.title==='稻香').id);
assert.equal(chatMusicCandidates(voice.message, {mood:'calm'}, playableTracks, catalog, undefined, voice.suggestedTrackId).tracks[0].title, '稻香');
assert.equal(chatMusicCandidates('播放《夏天》', {mood:'calm'}, playableTracks, catalog, undefined, voice.suggestedTrackId).tracks[0].title, '夏天');
assert.equal(voicePlaybackRequest('暂停音乐', true, '', playableTracks).message, '暂停音乐');
assert.equal(voicePlaybackRequest('播放刚才那首', true, '听听《稻香》', playableTracks).suggestedTrackId, playableTracks.find(t=>t.title==='稻香').id);
assert.equal(voicePlaybackRequest('放这首', true, '听听《稻香》', playableTracks).suggestedTrackId, playableTracks.find(t=>t.title==='稻香').id);
console.log('Chat playback intent, exact song matching, unavailable songs and rotation verified.');
